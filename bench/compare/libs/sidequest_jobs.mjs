// The job classes of the Sidequest adapter: Sidequest finds a job by its class and the module that exports it, so each
// job name is a static export. Each runs the handler of the current run: the inline runner runs jobs in this process.
// The names of the checks, then the 1000 of the performance runs (`job_0000`...`job_0999`, as perf.mjs names them),
// generated: one `export const job_NNNN = jobClass('job_NNNN');` each.
import { Job } from 'sidequest';

/** @type {(name: string, payload: any, signal?: AbortSignal) => Promise<void>} The handler of the current check */
let handler = async () => {};

/** @param {typeof handler} func */
export function setHandler(func) {
    handler = func;
}

/**
 * @param {string} name
 * @returns {typeof Job} A job class of this name.
 */
function jobClass(name) {
    const NamedJob = class extends Job {
        /**
         * @param {object} payload
         * @returns {Promise<void>}
         */
        run(payload) {
            return handler(name, payload, this.abortSignal);
        }
    };

    Object.defineProperty(NamedJob, 'name', { value: name });

    return NamedJob;
}

