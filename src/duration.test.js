import { expect, test } from 'vitest';
import { parseDuration } from './duration.js';

test.each([
    [0, 0],
    [1500, 1500],
    ['500ms', 500],
    ['5s', 5000],
    ['10m', 600_000],
    ['1h', 3_600_000],
    ['30d', 2_592_000_000],
    ['1.5s', 1500],
    ['4m30s', 270_000],
    ['1h 0m 1s', 3_601_000],
    ['1s', 1000],
    ['1ms', 1],
    ['1h 1m 1s', 3_661_000],
    ['1d1h1ms', 90_000_001],
    [' 1w 2d3h 4m5s6ms ', 788_645_006],
    ['0ms', 0],
    ['0d0s', 0],
    ['.5s', 500],
    ['0.0005s', 1],
    ['0.0004s', 0],
    ['0.0004s0.4ms', 1],
    [Number.MAX_SAFE_INTEGER, Number.MAX_SAFE_INTEGER],
    ['9007199254740991ms', Number.MAX_SAFE_INTEGER],
    ['9007199254740990ms', Number.MAX_SAFE_INTEGER - 1],
])('parses %o', (value, expected) => {
    expect(parseDuration(value)).toBe(expected);
});

test.each([
    [-1],
    [1.5],
    [Number.NaN],
    [Infinity],
    [''],
    ['soon'],
    ['-5s'],
    [null],
    [undefined],
    [{}],
    ['9999999999999d'],
    [Number.MAX_SAFE_INTEGER + 1],
    ['9007199254740992ms'],
    ['9007199254740s992ms'],
    [`${'9'.repeat(400)}ms`],
    [' '],
    ['1 days'],
    ['2 days'],
    ['1ms 1d'],
    ['30s1m'],
    ['1s 2s'],
    ['0s0s'],
    ['1m1ms1s'],
    ['1S'],
    ['1MS'],
    ['1 ms'],
    ['1\ts'],
    ['1s\n'],
    ['\n1s'],
    ['1h\t1s'],
    ['5s typo'],
    ['typo 5s'],
    ['1h -30m'],
    ['1h+30m'],
    ['+1s'],
    ['-0ms'],
    ['1h30'],
    ['1:30'],
    ['5'],
    ['1e3ms'],
    ['1,000ms'],
    ['1_000ms'],
    ['1month'],
    ['1y'],
    ['1us'],
    ['1ns'],
    ['1.s'],
    ['.s'],
    ['1s,1ms'],
    ['1s\u00A01ms'],
])('rejects %o', (value) => {
    expect(parseDuration(value)).toBeNull();
});
